package dev.vantage.client.cosmetics;

import dev.vantage.client.VantageClient;
import dev.vantage.client.module.Category;
import dev.vantage.client.module.Module;
import dev.vantage.client.setting.BooleanSetting;
import dev.vantage.client.setting.ColorSetting;
import dev.vantage.client.setting.EnumSetting;
import net.minecraft.client.renderer.entity.state.AvatarRenderState;
import net.minecraft.core.ClientAsset;
import net.minecraft.world.entity.animal.parrot.Parrot;
import net.minecraft.world.entity.player.PlayerSkin;
import org.jspecify.annotations.Nullable;

/**
 * Cape, hat and shoulder pet for your own player. Everything is drawn on your PC only: other players do not see
 * it, and nothing is sent to a server. Cape and hat art is generated by Vantage itself.
 */
public final class PlayerCosmeticsModule extends Module {
	/** Capes; the art is painted in code by {@link CosmeticTextures}. */
	public enum Cape {
		NONE("None"),
		VANTAGE("Vantage"),
		OCEAN("Ocean"),
		SUNSET("Sunset"),
		EMBER("Ember"),
		MINT("Mint"),
		GALAXY("Galaxy"),
		CHECKER("Checker");

		private final String label;

		Cape(String label) {
			this.label = label;
		}

		@Override
		public String toString() {
			return label;
		}
	}

	/** Hats; the models are built in code by {@link HatModels}. */
	public enum Hat {
		NONE("None"),
		TOP_HAT("Top hat"),
		CROWN("Crown"),
		HALO("Halo"),
		PARTY_HAT("Party hat"),
		BEANIE("Beanie");

		private final String label;

		Hat(String label) {
			this.label = label;
		}

		@Override
		public String toString() {
			return label;
		}
	}

	/** Animals that sit on your shoulder. */
	public enum Pet {
		NONE("None", null),
		RED_PARROT("Red parrot", Parrot.Variant.RED_BLUE),
		BLUE_PARROT("Blue parrot", Parrot.Variant.BLUE),
		GREEN_PARROT("Green parrot", Parrot.Variant.GREEN),
		CYAN_PARROT("Cyan parrot", Parrot.Variant.YELLOW_BLUE),
		GREY_PARROT("Grey parrot", Parrot.Variant.GRAY),
		BEE("Bee", null);

		private final String label;
		private final Parrot.@Nullable Variant parrot;

		Pet(String label, Parrot.@Nullable Variant parrot) {
			this.label = label;
			this.parrot = parrot;
		}

		public Parrot.@Nullable Variant parrot() {
			return parrot;
		}

		@Override
		public String toString() {
			return label;
		}
	}

	/** Which shoulder the pet sits on. */
	public enum Side {
		LEFT("Left"),
		RIGHT("Right"),
		BOTH("Both");

		private final String label;

		Side(String label) {
			this.label = label;
		}

		public boolean left() {
			return this != RIGHT;
		}

		public boolean right() {
			return this != LEFT;
		}

		@Override
		public String toString() {
			return label;
		}
	}

	public final EnumSetting<Cape> cape = add(new EnumSetting<>("cape", "Cape", "A cape made by Vantage. None keeps your Minecraft cape.", Cape.NONE));
	public final EnumSetting<Hat> hat = add(new EnumSetting<>("hat", "Hat", "A hat on your head.", Hat.NONE));
	public final ColorSetting hatColor = add(new ColorSetting("hatColor", "Hat colour",
		"Colour of the band, gems, party hat or beanie.", 0xFF7C5CFF));
	public final BooleanSetting hideHatUnderHelmet = add(new BooleanSetting("hideHatUnderHelmet", "Hide hat under helmet",
		"Do not draw the hat while something is on your head.", true));
	public final EnumSetting<Pet> pet = add(new EnumSetting<>("pet", "Pet", "An animal that sits on your shoulder.", Pet.NONE));
	public final EnumSetting<Side> petSide = add(new EnumSetting<>("petSide", "Shoulder", "Which shoulder the pet sits on.", Side.LEFT));

	public PlayerCosmeticsModule() {
		super("cosmetics", "Cosmetics", "Cape, hat and shoulder pet for your own player. Only you can see them.", Category.VISUAL, true);
		hatColor.visibleWhen(() -> hat.get() != Hat.NONE);
		hideHatUnderHelmet.visibleWhen(() -> hat.get() != Hat.NONE);
		petSide.visibleWhen(() -> pet.get() != Pet.NONE);
	}

	/** Returns the module when {@code state} belongs to your own player and cosmetics are on, else null. */
	public static @Nullable PlayerCosmeticsModule activeFor(AvatarRenderState state) {
		if (!VantageClient.isReady() || MC.player == null || state.id != MC.player.getId()) {
			return null;
		}
		PlayerCosmeticsModule module = VantageClient.get().modules().get(PlayerCosmeticsModule.class);
		return module != null && module.isEnabled() ? module : null;
	}

	/** Puts the cape and parrots into your player's render state (called after vanilla filled it). */
	public void apply(AvatarRenderState state) {
		if (!isEnabled()) {
			return;
		}
		if (cape.get() != Cape.NONE) {
			ClientAsset.Texture texture = CosmeticTextures.cape(cape.get());
			PlayerSkin skin = state.skin;
			// A null elytra texture makes vanilla use the cape texture for the elytra, which our art also covers.
			state.skin = new PlayerSkin(skin.body(), texture, null, skin.model(), skin.secure());
			state.showCape = true;
		}
		Parrot.Variant parrot = pet.get().parrot();
		if (parrot != null) {
			// Real parrots keep their place; the cosmetic only fills an empty shoulder.
			if (petSide.get().left() && state.parrotOnLeftShoulder == null) {
				state.parrotOnLeftShoulder = parrot;
			}
			if (petSide.get().right() && state.parrotOnRightShoulder == null) {
				state.parrotOnRightShoulder = parrot;
			}
		}
	}
}
